#!/bin/sh
#
# 跑一个测试程序，并确认它**真的跑了断言**。
#
# 为什么要这层包装：
#
#   空的或损坏的测试二进制会"退出码 0 且什么都不打印"，
#   只看退出码的话这等价于"0 项测试、0 项失败" —— 一片绿灯，
#   其实什么都没测。这种假通过比失败危险得多：
#   测试数悄悄少掉 38 项，只有自己去数总数才会发现。
#
#   实际就发生过：tests/dept 曾是一个 0 字节文件（构建被中断留下的残骸），
#   make test 全程退出 0，总数从 2562 掉到 2524 也没人报错。
#
# 所以这里强制三条：
#   1) 输出里必须出现"通过 N 项"
#   2) N > 0
#   3) 退出码为 0
#
out=$("$@" 2>&1)
rc=$?
echo "$out"

if [ $rc -ne 0 ]; then
    echo "!! 退出码 $rc : $*"
    exit 1
fi

n=$(printf '%s\n' "$out" | sed -n 's/.*通过 \([0-9][0-9]*\) 项.*/\1/p' | tail -1)

if [ -z "$n" ]; then
    echo "!! 没有输出测试统计（二进制为空/损坏/不是测试程序？）: $*"
    exit 1
fi

if [ "$n" -eq 0 ]; then
    echo "!! 一项断言都没跑: $*"
    exit 1
fi

exit 0
